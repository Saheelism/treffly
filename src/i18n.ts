export const dict = { en, de };
export function detectLang(): Lang {
  try { const s = localStorage.getItem('treffly-lang'); if (s === 'en' || s === 'de') return s; } catch {}
  return navigator.language?.toLowerCase().startsWith('de') ? 'de' : 'en';
}
